const assert = require('node:assert/strict')
const { installEnv, parseResult } = require('./install-dependencies.cjs')
const parent = { Path:'C:\\node', https_proxy:'http://old:1', ALL_PROXY:'socks5://old:2', npm_config_proxy:'http://old:3', npm_config_https_proxy:'http://old:4', npm_config_noproxy:'*', NODE_EXTRA_CA_CERTS:'C:\\corp.pem' }
const proxy = parseResult('\uFEFF{"http":"http://127.0.0.1:7890/","https":"http://127.0.0.1:7891/"}')
const env = installEnv(parent, proxy)
assert.equal(env.npm_config_proxy,proxy.http)
assert.equal(env.npm_config_https_proxy,proxy.https)
assert.equal(env.HTTPS_PROXY,proxy.https)
assert.equal(env.https_proxy,undefined)
assert.equal(env.ALL_PROXY,undefined)
assert.equal(env.npm_config_noproxy,'localhost,127.0.0.1,::1')
assert.equal(env.NODE_EXTRA_CA_CERTS,parent.NODE_EXTRA_CA_CERTS)
assert.equal(parent.npm_config_proxy,'http://old:3')
const direct=installEnv(parent,{http:'',https:''})
assert.equal(direct.npm_config_proxy,'')
assert.equal(direct.HTTPS_PROXY,'')
assert.throws(()=>parseResult('{"http":"file:///bad","https":""}'))
assert.throws(()=>parseResult('{"http":null,"https":""}'))
console.log('Installer proxy tests: 12/12 passed (pure logic; Windows API not exercised)')
